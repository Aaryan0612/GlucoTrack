export function getRandomMotivation(excludeIndex = -1) {
  if (excludeIndex >= 0 && MOTIVATIONAL_DATA.length > 1) {
    const pool = MOTIVATIONAL_DATA.filter((_, idx) => idx !== excludeIndex);
    const randomItem = pool[Math.floor(Math.random() * pool.length)];
    return {
      item: randomItem,
      index: MOTIVATIONAL_DATA.indexOf(randomItem)
    };
  }
  const index = Math.floor(Math.random() * MOTIVATIONAL_DATA.length);
  return {
    item: MOTIVATIONAL_DATA[index],
    index
  };
}
